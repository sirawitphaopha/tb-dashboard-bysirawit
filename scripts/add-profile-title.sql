-- เพิ่มคอลัมน์ "คำนำหน้าชื่อ" (title) ในตาราง profiles
-- ผู้ใช้เลือกเอง เช่น ภก./ภญ. (เภสัช), นพ./พญ. (แพทย์), นาย/นาง/นางสาว (กลุ่มไม่มีตัวย่อ)
-- รันครั้งเดียวใน Supabase SQL Editor
-- ════════════════════════════════════════════════════════════════

alter table profiles add column if not exists title text;

-- หมายเหตุ:
-- - user เก่าที่ยังไม่มีค่า (title = null) โค้ดจะแสดงคำนำหน้าตัวแรกของวิชาชีพให้ชั่วคราว
--   (เภสัช → ภก.) แล้ว admin หรือ user แก้ให้ถูกต้องเองในหน้าโปรไฟล์/จัดการผู้ใช้
-- - ไม่กระทบ RLS policy เดิม (เป็นแค่คอลัมน์ข้อมูลทั่วไป)
